create function public.ingest_provider_message(
  p_provider_connection_id bigint,
  p_contact_external_id text,
  p_contact_handle text,
  p_contact_name text,
  p_avatar_url text,
  p_conversation_external_id text,
  p_subject text,
  p_message_external_id text,
  p_direction public.message_direction,
  p_content text,
  p_occurred_at timestamptz,
  p_metadata jsonb default '{}'::jsonb
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  connection_row public.provider_connections%rowtype;
  contact_row public.contacts%rowtype;
  conversation_row public.conversations%rowtype;
  message_row public.messages%rowtype;
  event_time timestamptz := coalesce(p_occurred_at, now());
  message_status public.message_delivery_status;
  message_preview text;
begin
  select pc.* into connection_row
  from public.provider_connections pc
  where pc.id = p_provider_connection_id;
  if not found then
    raise exception 'provider connection not found' using errcode = 'P0002';
  end if;
  if connection_row.status <> 'connected' then
    raise exception 'provider connection is not active' using errcode = '55000';
  end if;
  if p_contact_external_id is null or length(btrim(p_contact_external_id)) = 0 then
    raise exception 'contact external id is required' using errcode = '22023';
  end if;
  if p_conversation_external_id is null or length(btrim(p_conversation_external_id)) = 0 then
    raise exception 'conversation external id is required' using errcode = '22023';
  end if;
  if p_direction is null or p_direction not in ('inbound', 'outbound') then
    raise exception 'provider messages must be inbound or outbound' using errcode = '22023';
  end if;
  if p_content is null or length(p_content) > 50000 then
    raise exception 'message content exceeds 50000 characters' using errcode = '22023';
  end if;

  insert into public.contacts (
    workspace_id, provider_connection_id, external_id, handle, display_name, avatar_url
  ) values (
    connection_row.workspace_id,
    connection_row.id,
    p_contact_external_id,
    coalesce(nullif(btrim(p_contact_handle), ''), p_contact_external_id),
    nullif(btrim(p_contact_name), ''),
    p_avatar_url
  )
  on conflict (provider_connection_id, external_id) do update
    set handle = coalesce(nullif(excluded.handle, ''), public.contacts.handle),
        display_name = coalesce(excluded.display_name, public.contacts.display_name),
        avatar_url = coalesce(excluded.avatar_url, public.contacts.avatar_url),
        updated_at = now()
  returning * into contact_row;

  insert into public.conversations (
    workspace_id, provider_connection_id, contact_id, provider, external_id, subject,
    last_message_at, last_message_preview
  ) values (
    connection_row.workspace_id,
    connection_row.id,
    contact_row.id,
    connection_row.provider,
    p_conversation_external_id,
    p_subject,
    event_time,
    ''
  )
  on conflict (provider_connection_id, external_id) do update
    set subject = coalesce(excluded.subject, public.conversations.subject),
        updated_at = now()
  returning * into conversation_row;

  message_status := case
    when p_direction = 'outbound' then 'sent'::public.message_delivery_status
    else null
  end;

  if p_message_external_id is null then
    insert into public.messages (
      workspace_id, provider_connection_id, conversation_id, direction, content,
      author_name, delivery_status, sent_at, metadata, created_at
    ) values (
      connection_row.workspace_id, connection_row.id, conversation_row.id, p_direction,
      p_content,
      case when p_direction = 'outbound' then 'You'
        else coalesce(nullif(p_contact_name, ''), contact_row.handle) end,
      message_status, case when p_direction = 'outbound' then event_time else null end,
      coalesce(p_metadata, '{}'::jsonb), event_time
    ) returning * into message_row;
  else
    insert into public.messages (
      workspace_id, provider_connection_id, conversation_id, external_id, direction,
      content, author_name, delivery_status, sent_at, metadata, created_at
    ) values (
      connection_row.workspace_id, connection_row.id, conversation_row.id, p_message_external_id,
      p_direction, p_content,
      case when p_direction = 'outbound' then 'You'
        else coalesce(nullif(p_contact_name, ''), contact_row.handle) end,
      message_status, case when p_direction = 'outbound' then event_time else null end,
      coalesce(p_metadata, '{}'::jsonb), event_time
    )
    on conflict (provider_connection_id, external_id) where external_id is not null
      do nothing
    returning * into message_row;
  end if;

  if message_row.id is null then
    select m.* into message_row
    from public.messages m
    where m.provider_connection_id = connection_row.id
      and m.external_id = p_message_external_id;
    return jsonb_build_object(
      'conversation_id', conversation_row.id,
      'message_id', message_row.id,
      'duplicate', true
    );
  end if;

  message_preview := left(regexp_replace(
    coalesce(nullif(p_content, ''), '[attachment]'), '\s+', ' ', 'g'
  ), 180);

  update public.conversations
  set last_message_at = greatest(last_message_at, event_time),
      last_message_preview = case
        when event_time >= last_message_at then message_preview
        else last_message_preview
      end,
      unread_count = case
        when p_direction = 'inbound' then unread_count + 1
        else unread_count
      end,
      status = case
        when p_direction = 'inbound' and status in ('resolved', 'pending', 'snoozed') then 'open'
        else status
      end,
      snoozed_until = case
        when p_direction = 'inbound' then null
        else snoozed_until
      end,
      updated_at = now()
  where id = conversation_row.id;

  update public.provider_connections
  set last_synced_at = now(), updated_at = now()
  where id = connection_row.id;

  return jsonb_build_object(
    'conversation_id', conversation_row.id,
    'message_id', message_row.id,
    'duplicate', false
  );
end;
$$;

create function public.set_conversation_status(
  p_conversation_id bigint,
  p_status text,
  p_snoozed_until timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  conversation_row public.conversations%rowtype;
begin
  if current_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;
  if p_status is null or p_status not in ('open', 'pending', 'resolved', 'snoozed') then
    raise exception 'status must be open, pending, resolved, or snoozed' using errcode = '22023';
  end if;
  if p_status = 'snoozed' and (p_snoozed_until is null or p_snoozed_until <= now()) then
    raise exception 'snoozed conversations require a future wake time' using errcode = '22023';
  end if;

  update public.conversations c
  set status = p_status,
      snoozed_until = case when p_status = 'snoozed' then p_snoozed_until else null end,
      updated_at = now()
  where c.id = p_conversation_id
    and public.is_workspace_member(c.workspace_id)
  returning c.* into conversation_row;

  if not found then
    raise exception 'conversation not found' using errcode = 'P0002';
  end if;

  return jsonb_build_object(
    'id', conversation_row.id,
    'status', conversation_row.status,
    'snoozed_until', conversation_row.snoozed_until,
    'updated_at', conversation_row.updated_at
  );
end;
$$;

create function public.enqueue_reply(
  p_conversation_id bigint,
  p_content text,
  p_client_request_id uuid,
  p_scheduled_at timestamptz default null
)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_user_id uuid := auth.uid();
  current_profile_id bigint;
  conversation_row public.conversations%rowtype;
  message_row public.messages%rowtype;
  message_status public.message_delivery_status;
begin
  if current_user_id is null then
    raise exception 'authentication required' using errcode = '28000';
  end if;
  select p.id into current_profile_id
  from public.profiles p
  where p.auth_user_id = current_user_id;
  if current_profile_id is null then
    raise exception 'user profile not found' using errcode = '28000';
  end if;
  if p_content is null or length(btrim(p_content)) = 0 then
    raise exception 'reply content is required' using errcode = '22023';
  end if;
  if p_client_request_id is null then
    raise exception 'client request id is required' using errcode = '22023';
  end if;
  if length(p_content) > 50000 then
    raise exception 'reply exceeds 50000 characters' using errcode = '22023';
  end if;

  select c.* into conversation_row
  from public.conversations c
  join public.provider_connections pc
    on pc.id = c.provider_connection_id
   and pc.workspace_id = c.workspace_id
  where c.id = p_conversation_id
    and public.is_workspace_member(c.workspace_id)
  for update;

  if not found then
    raise exception 'conversation not found' using errcode = 'P0002';
  end if;
  if conversation_row.status = 'resolved' then
    raise exception 'resolved conversations cannot receive replies' using errcode = '22023';
  end if;
  if not exists (
    select 1 from public.provider_connections pc
    where pc.id = conversation_row.provider_connection_id
      and pc.status = 'connected'
  ) then
    raise exception 'provider connection is not active' using errcode = '55000';
  end if;

  message_status := case
    when p_scheduled_at is not null and p_scheduled_at > now() then 'scheduled'::public.message_delivery_status
    else 'queued'::public.message_delivery_status
  end;

  insert into public.messages (
    workspace_id, provider_connection_id, conversation_id, client_request_id,
    direction, content, author_user_id, author_name, delivery_status, scheduled_at
  ) values (
    conversation_row.workspace_id,
    conversation_row.provider_connection_id,
    conversation_row.id,
    p_client_request_id,
    'outbound',
    p_content,
    current_profile_id,
    (select p.full_name from public.profiles p where p.id = current_profile_id),
    message_status,
    p_scheduled_at
  )
  on conflict (conversation_id, client_request_id) do nothing
  returning * into message_row;

  if message_row.id is null then
    select m.* into message_row
    from public.messages m
    where m.conversation_id = p_conversation_id
      and m.client_request_id = p_client_request_id;
    if message_row.id is null or message_row.direction <> 'outbound' then
      raise exception 'request id conflicts with another message' using errcode = '23505';
    end if;
    return jsonb_build_object(
      'id', message_row.id,
      'conversation_id', message_row.conversation_id,
      'inbox_id', conversation_row.provider_connection_id,
      'content', message_row.content,
      'author_user_id', message_row.author_user_id,
      'author_name', message_row.author_name,
      'delivery_status', message_row.delivery_status,
      'created_at', message_row.created_at,
      'duplicate', true
    );
  end if;

  insert into public.outbox_jobs (workspace_id, message_id, available_at)
  values (
    message_row.workspace_id,
    message_row.id,
    coalesce(p_scheduled_at, now())
  );

  update public.conversations
  set last_message_at = case
        when message_status = 'queued' then now()
        else last_message_at
      end,
      last_message_preview = case
        when message_status = 'queued' then left(regexp_replace(p_content, '\s+', ' ', 'g'), 180)
        else last_message_preview
      end,
      updated_at = now()
  where id = conversation_row.id;

  return jsonb_build_object(
    'id', message_row.id,
    'conversation_id', message_row.conversation_id,
    'inbox_id', conversation_row.provider_connection_id,
    'content', message_row.content,
    'author_user_id', message_row.author_user_id,
    'author_name', message_row.author_name,
    'delivery_status', message_row.delivery_status,
    'created_at', message_row.created_at,
    'duplicate', false
  );
end;
$$;

