create function public.is_workspace_member(target_workspace_id bigint)
returns boolean
language sql
stable
security definer
set search_path = ''
as $$
  select exists (
    select 1
    from public.workspace_members wm
    where wm.workspace_id = target_workspace_id
      and exists (
        select 1 from public.profiles p
        where p.id = wm.user_id and p.auth_user_id = auth.uid()
      )
  );
$$;

create function public.create_personal_workspace_for_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
declare
  new_workspace_id bigint;
  new_profile_id bigint;
begin
  insert into public.profiles (auth_user_id, full_name, avatar_url)
  values (
    new.id,
    nullif(new.raw_user_meta_data ->> 'full_name', ''),
    nullif(new.raw_user_meta_data ->> 'avatar_url', '')
  )
  on conflict (auth_user_id) do update
    set full_name = excluded.full_name,
        avatar_url = excluded.avatar_url,
        updated_at = now();

  select p.id into new_profile_id
  from public.profiles p
  where p.auth_user_id = new.id;

  insert into public.workspaces (name, created_by)
  values (
    coalesce(nullif(new.raw_user_meta_data ->> 'account_name', ''), 'Personal workspace'),
    new_profile_id
  )
  returning id into new_workspace_id;

  insert into public.workspace_members (workspace_id, user_id, role)
  values (new_workspace_id, new_profile_id, 'owner');

  return new;
end;
$$;

